static void lcm_init(void)
{
	lcd_power_en(1);
	MDELAY(5);
	display_bias_set(1);
	MDELAY(30);
// #if defined(CONFIG_TOUCHSCREEN_CHIPONE)
// 	cts_lcm_set_reset(1);
// #endif
	MDELAY(20);
	lcd_reset(1);
	MDELAY(20);
	lcd_reset(0);
	MDELAY(50);
	lcd_reset(1);

	MDELAY(120);//Must > 5ms
	init_lcm_registers();
	MDELAY(50);
	mid_bb_lcd_bl_en(1);
}

static void lcm_suspend(void)
{
	unsigned int data_array[16];
	mid_bb_lcd_bl_en(0);
	MDELAY(50);
	data_array[0] = 0x0AAC1500;
	dsi_set_cmdq(data_array, 1, 1);

	data_array[0] = 0x00280500;
	dsi_set_cmdq(data_array, 1, 1);
	MDELAY(20);
	data_array[0] = 0x00100500;
	dsi_set_cmdq(data_array, 1, 1);

	MDELAY(120);
	lcd_reset(0);
	MDELAY(50);
// #if defined(CONFIG_TOUCHSCREEN_CHIPONE)
// 	cts_lcm_set_reset(0);
// #endif
	MDELAY(20);
	display_bias_set(0);
	MDELAY(10);
	lcd_power_en(0);
	MDELAY(20);
}

static void lcm_resume(void)
{
	lcm_init();
}

